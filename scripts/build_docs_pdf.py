import markdown
from pygments.formatters import HtmlFormatter

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_OUTPUT = ROOT / "docs" / "Thiago Afonso - AI Engineer.pdf"

TITLE = "Empório da Música"
SUBTITLE = "Customer support agent — technical documentation"
FOOTNOTE = "Technical challenge · AI Engineer · Artefact"
REPO = "github.com/Thafonso/desafio_artefact"
AUTHOR = "Thiago Afonso"

BROWSER_CANDIDATES = [
    r"C:\Program Files\Google\Chrome\Application\chrome.exe",
    r"C:\Program Files (x86)\Google\Chrome\Application\chrome.exe",
    r"C:\Program Files (x86)\Microsoft\Edge\Application\msedge.exe",
    r"C:\Program Files\Microsoft\Edge\Application\msedge.exe",
]

MD_EXTENSIONS = ["extra", "sane_lists", "toc", "codehilite"]
MD_CONFIG = {
    "codehilite": {"guess_lang": False, "css_class": "highlight"},
    "toc": {"permalink": False, "toc_depth": "1-3"},
}


def find_browser() -> str:
    for name in ("chrome", "msedge", "chromium", "google-chrome"):
        found = shutil.which(name)
        if found:
            return found
    for path in BROWSER_CANDIDATES:
        if os.path.isfile(path):
            return path
    sys.exit("No Chrome/Edge binary found - needed to render the PDF.")


def demote_headings(text: str) -> str:
    """Push every ATX heading one level down, skipping fenced code blocks."""
    out, in_fence = [], False
    for line in text.splitlines():
        if line.lstrip().startswith("```"):
            in_fence = not in_fence
        if not in_fence and line.startswith("#"):
            line = "#" + line
        out.append(line)
    return "\n".join(out)


def collect_markdown() -> str:
    """README first, then every example file as a sub-section of its own part."""
    parts = [(ROOT / "README.md").read_text(encoding="utf-8")]

    examples = sorted((ROOT / "examples").glob("*.md"))
    if examples:
        parts.append(
            '<div class="page-break"></div>\n\n'
            "# Appendix — example conversations\n\n"
            "Full transcripts of the sessions cited in *Example "
            "interactions*, generated by `scripts/generate_examples.py`. The "
            "conversations are in Portuguese — see *Language convention*.\n"
        )
        parts.extend(
            demote_headings(path.read_text(encoding="utf-8")) for path in examples
        )

    return "\n\n---\n\n".join(parts)


def build_html(body: str, toc: str) -> str:
    pygments_css = HtmlFormatter(style="friendly").get_style_defs(".highlight")
    today = date.today().strftime("%B %d, %Y")
    return HTML_TEMPLATE.format(
        title=TITLE,
        subtitle=SUBTITLE,
        footnote=FOOTNOTE,
        repo=REPO,
        author=AUTHOR,
        today=today,
        pygments_css=pygments_css,
        toc=toc,
        body=body,
    )


def render_pdf(html: str, browser: str, destination: Path) -> None:
    with tempfile.TemporaryDirectory() as tmp:
        tmp_path = Path(tmp)
        source = tmp_path / "docs.html"
        source.write_text(html, encoding="utf-8")
        raw_pdf = tmp_path / "docs.pdf"

        subprocess.run(
            [
                browser,
                "--headless=new",
                "--disable-gpu",
                "--no-pdf-header-footer",
                f"--user-data-dir={tmp_path / 'profile'}",
                f"--print-to-pdf={raw_pdf}",
                "--virtual-time-budget=4000",
                source.as_uri(),
            ],
            check=True,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
        )

        if not raw_pdf.exists():
            sys.exit("The browser did not produce a PDF.")

        destination.parent.mkdir(parents=True, exist_ok=True)
        add_page_numbers(raw_pdf, destination)


def add_page_numbers(source: Path, destination: Path) -> None:
    """Stamp 'n / total' at the bottom of every page but the cover."""
    try:
        from pypdf import PdfReader, PdfWriter
        from reportlab.lib.colors import HexColor
        from reportlab.pdfgen import canvas
    except ImportError:
        shutil.copyfile(source, destination)
        print("pypdf/reportlab missing - PDF written without page numbers.")
        return

    reader = PdfReader(str(source))
    total = len(reader.pages)
    writer = PdfWriter()

    for index, page in enumerate(reader.pages, start=1):
        if index > 1:
            width = float(page.mediabox.width)
            height = float(page.mediabox.height)
            buffer = io.BytesIO()
            overlay = canvas.Canvas(buffer, pagesize=(width, height))
            overlay.setFont("Helvetica", 7.5)
            overlay.setFillColor(HexColor("#8a90a0"))
            overlay.drawString(48, 26, TITLE)
            overlay.drawRightString(width - 48, 26, f"{index} / {total}")
            overlay.save()
            buffer.seek(0)
            page.merge_page(PdfReader(buffer).pages[0])
        writer.add_page(page)

    writer.add_metadata(
        {
            "/Title": f"{TITLE} - {SUBTITLE}",
            "/Author": AUTHOR,
            "/Subject": FOOTNOTE,
        }
    )
    with open(destination, "wb") as handle:
        writer.write(handle)


