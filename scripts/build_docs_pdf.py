def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "-o",
        "--output",
        type=Path,
        default=DEFAULT_OUTPUT,
        help="destination path (default: docs/Thiago Afonso - AI Engineer.pdf)",
    )
    args = parser.parse_args()

    md = markdown.Markdown(extensions=MD_EXTENSIONS, extension_configs=MD_CONFIG)
    body = md.convert(collect_markdown())
    render_pdf(build_html(body, md.toc), find_browser(), args.output)

    size_kb = args.output.stat().st_size / 1024
    print(f"PDF written to {args.output} ({size_kb:.0f} KB)")


if __name__ == "__main__":
    main()
