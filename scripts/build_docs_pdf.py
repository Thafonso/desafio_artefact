"""Build a single PDF out of the project documentation.

Concatenates README.md and the conversation examples into one HTML document,
renders it with headless Chrome (or Edge) and stamps page numbers on top.

    python scripts/build_docs_pdf.py [-o docs/output.pdf]

Requirements: markdown, pygments, pypdf, reportlab, and Chrome or Edge.
"""

from __future__ import annotations

import argparse
